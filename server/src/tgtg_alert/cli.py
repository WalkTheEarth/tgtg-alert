"""Command line interface.

Everything a self-hoster needs: set up, log in to TGTG, manage watches, pair a
phone, poll, and serve. Deliberately dependency-light (argparse, not click) so
`docker run` starts fast and there is nothing to learn beyond `--help`.
"""

from __future__ import annotations

import argparse
import json
import logging
import os
import secrets
import socket
import sys
from pathlib import Path

from . import __version__, db
from .config import Config

log = logging.getLogger("tgtg_alert")

ENV_FILENAME = ".env"


# -- helpers -------------------------------------------------------------


def load_env_file(path: Path | None = None) -> None:
    """Load KEY=VALUE lines into the environment without clobbering real env vars.

    A tiny stand-in for python-dotenv: this project needs exactly one file in
    one format, and a dependency for that would be silly.
    """
    candidates = [path] if path else [Path.cwd() / ENV_FILENAME, Path.home() / ".tgtg-alert" / ENV_FILENAME]
    for candidate in candidates:
        if not candidate or not candidate.is_file():
            continue
        for line in candidate.read_text().splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            if key and key not in os.environ:
                os.environ[key] = value


def setup_logging(level: str) -> None:
    logging.basicConfig(
        level=getattr(logging, level, logging.INFO),
        format="%(asctime)s %(levelname)-7s %(name)s: %(message)s",
        datefmt="%H:%M:%S",
    )


def local_ip() -> str:
    """Best-effort LAN address, so the pairing QR works without configuration."""
    sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
    try:
        # No packets are sent; this just picks the interface that would route out.
        sock.connect(("8.8.8.8", 80))
        return sock.getsockname()[0]
    except OSError:
        return "127.0.0.1"
    finally:
        sock.close()


def get_config() -> Config:
    config = Config.from_env()
    config.ensure_dirs()
    return config


def masking(secret: str | None, keep: int = 6) -> str:
    if not secret:
        return "(none)"
    if len(secret) <= keep * 2:
        return "*" * len(secret)
    return f"{secret[:keep]}...{secret[-keep:]}"


# -- commands ------------------------------------------------------------


def cmd_init(args: argparse.Namespace) -> int:
    config = get_config()
    env_path = Path(args.env_file).resolve()

    if env_path.exists() and not args.force:
        print(f"{env_path} already exists; leaving it alone (use --force to rewrite).")
        return 0

    token = secrets.token_urlsafe(32)
    env_path.write_text(
        "# Generated by `tgtg-alert init`. Keep this file private.\n"
        f"TGTG_DATA_DIR={config.data_dir}\n"
        f"TGTG_API_TOKEN={token}\n"
        f"TGTG_POLL_INTERVAL={config.poll_interval}\n"
        f"TGTG_PORT={config.port}\n"
    )
    env_path.chmod(0o600)

    db.init_db(config.db_path)
    print(f"Created {env_path}")
    print(f"Database at {config.db_path}")
    print()
    print("Next: `tgtg-alert login` to connect your Too Good To Go account.")
    return 0


def cmd_login(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    # Imported here so `--help` and `init` stay instant.
    from tgtg import TgtgClient

    email = args.email or input("Too Good To Go account email: ").strip()
    if not email:
        print("An email is required.", file=sys.stderr)
        return 2

    print()
    print("Requesting a login code from Too Good To Go...")
    print("(Check your inbox -- TGTG will email a 6-digit PIN.)")
    print()

    try:
        client = TgtgClient(email=email)
        credentials = client.get_credentials()
    except Exception as exc:  # noqa: BLE001 - surfaced to the operator verbatim
        print(f"\nLogin failed: {exc}", file=sys.stderr)
        return 1

    refreshed = getattr(client, "last_time_token_refreshed", None)
    with db.transaction(config.db_path) as conn:
        conn.execute("DELETE FROM tgtg_credentials")
        conn.execute(
            """
            INSERT INTO tgtg_credentials
                (id, email, access_token, refresh_token, cookie,
                 last_time_token_refreshed, user_agent)
            VALUES (1, ?, ?, ?, ?, ?, ?)
            """,
            (
                email,
                credentials["access_token"],
                credentials["refresh_token"],
                credentials["cookie"],
                refreshed.isoformat() if refreshed else None,
                getattr(client, "user_agent", None),
            ),
        )

    print()
    print(f"Logged in as {email}. Credentials stored in {config.db_path}.")
    print("Note: this database now contains a live session -- treat it as a secret.")
    return 0


def cmd_watch_add(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    latitude = args.lat
    longitude = args.lon
    if latitude is None or longitude is None:
        print("Both --lat and --lon are required (the centre of your search).", file=sys.stderr)
        return 2

    max_price_minor = None
    if args.max_price is not None:
        max_price_minor = int(round(args.max_price * 100))

    with db.transaction(config.db_path) as conn:
        cur = conn.execute(
            """
            INSERT INTO watches
                (label, store_pattern, bag_pattern, max_price_minor,
                 latitude, longitude, radius_km, notify_on_increase)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?)
            """,
            (
                args.label or "",
                args.store,
                args.bag,
                max_price_minor,
                latitude,
                longitude,
                args.radius,
                1 if args.notify_on_increase else 0,
            ),
        )
        watch_id = cur.lastrowid

    print(f"Added watch #{watch_id}.")
    print("The first poll records what is already available without alerting;")
    print("after that you will be notified when something shows up.")
    return 0


def cmd_watch_list(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    with db.closing_connection(config.db_path) as conn:
        rows = conn.execute(
            """
            SELECT w.*,
                   (SELECT COUNT(*) FROM observations o WHERE o.watch_id = w.id) AS seen,
                   (SELECT COUNT(*) FROM observations o
                     WHERE o.watch_id = w.id AND o.last_quantity > 0)        AS in_stock
              FROM watches w ORDER BY w.id
            """
        ).fetchall()

    if not rows:
        print("No watches yet. Add one with `tgtg-alert watch add`.")
        return 0

    print(f"{'ID':>3}  {'ON':>2}  {'SEARCH':<34} {'RADIUS':>7}  {'TRACKED':>7}  {'IN STOCK':>8}")
    print("-" * 74)
    for r in rows:
        bits = []
        if r["store_pattern"]:
            bits.append(f"store~{r['store_pattern']!r}")
        if r["bag_pattern"]:
            bits.append(f"bag~{r['bag_pattern']!r}")
        if r["max_price_minor"] is not None:
            bits.append(f"<= {r['max_price_minor'] / 100:.2f}")
        if r["label"]:
            bits.insert(0, r["label"])
        desc = " ".join(bits) or "(any bag)"
        state = "yes" if r["baselined_at"] else "new"
        print(
            f"{r['id']:>3}  {'on' if r['enabled'] else 'off':>2}  {desc[:34]:<34} "
            f"{r['radius_km']:>5}km  {r['seen']:>7}  {r['in_stock']:>8}"
            + ("" if state == "yes" else "   (awaiting first poll)")
        )
    return 0


def cmd_watch_update(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    fields, values = [], []
    if args.enable:
        fields.append("enabled = 1")
    if args.disable:
        fields.append("enabled = 0")
    if args.rebaseline:
        # Forget the current stock picture so the next poll re-surveys quietly
        # instead of firing an alert for everything that is merely still there.
        fields.append("baselined_at = NULL")
    if args.store is not None:
        fields.append("store_pattern = ?")
        values.append(args.store or None)
    if args.bag is not None:
        fields.append("bag_pattern = ?")
        values.append(args.bag or None)

    if not fields:
        print("Nothing to change. See --help for options.", file=sys.stderr)
        return 2

    values.append(args.watch_id)
    with db.transaction(config.db_path) as conn:
        cur = conn.execute(f"UPDATE watches SET {', '.join(fields)} WHERE id = ?", values)
        if cur.rowcount == 0:
            print(f"No watch with id {args.watch_id}.", file=sys.stderr)
            return 1

    if args.rebaseline:
        with db.transaction(config.db_path) as conn:
            conn.execute("DELETE FROM observations WHERE watch_id = ?", (args.watch_id,))

    print(f"Updated watch #{args.watch_id}.")
    return 0


def cmd_watch_rm(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)
    with db.transaction(config.db_path) as conn:
        cur = conn.execute("DELETE FROM watches WHERE id = ?", (args.watch_id,))
    if cur.rowcount == 0:
        print(f"No watch with id {args.watch_id}.", file=sys.stderr)
        return 1
    print(f"Removed watch #{args.watch_id}.")
    return 0


def cmd_devices(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    if args.rm:
        with db.transaction(config.db_path) as conn:
            conn.execute("DELETE FROM devices WHERE id = ?", (args.rm,))
        print(f"Removed device #{args.rm}.")
        return 0

    with db.closing_connection(config.db_path) as conn:
        rows = conn.execute("SELECT * FROM devices ORDER BY id").fetchall()

    if not rows:
        print("No paired devices. Run `tgtg-alert pair` and scan the code in the app.")
        return 0

    for r in rows:
        print(f"#{r['id']}  {r['platform'] or '?':<8} {r['label'] or '':<18} {masking(r['expo_push_token'])}")
    return 0


def cmd_pair(args: argparse.Namespace) -> int:
    config = get_config()
    db.init_db(config.db_path)

    base = args.url or f"http://{local_ip()}:{config.port}"
    payload = json.dumps({"url": base, "token": config.api_token, "v": 1})
    link = f"tgtgalert://pair?d={payload}"

    print()
    print("Scan this with the Too Good To Go Alert app:")
    print()
    try:
        import qrcode

        qr = qrcode.QRCode(border=1)
        qr.add_data(link)
        qr.make(fit=True)
        qr.print_ascii(invert=True)
    except Exception:  # noqa: BLE001 - the text fallback is always usable
        print("(Could not render a QR code; enter these values manually.)")

    print()
    print(f"  Server URL : {base}")
    print(f"  API token  : {config.api_token}")
    print()
    print("The phone must be able to reach that URL. On a home LAN that works as-is;")
    print("otherwise put this behind a reverse proxy with TLS and pass --url.")
    return 0


def cmd_poll(args: argparse.Namespace) -> int:
    config = get_config()
    setup_logging(config.log_level)
    db.init_db(config.db_path)

    from .poller import Poller
    from .tgtg_source import CredentialsMissing

    poller = Poller(config, webhook_url=os.environ.get("TGTG_WEBHOOK_URL"))
    try:
        stats = poller.run_once(dry_run=args.dry_run)
    except CredentialsMissing as exc:
        print(f"\n{exc}", file=sys.stderr)
        return 1

    print(
        f"\n{stats.watches} watch(es), {stats.buckets} API call group(s), "
        f"{stats.items_seen} item(s), {stats.matched} match(es), {stats.alerts} alert(s)."
    )
    return 0 if stats.errors == 0 else 1


def cmd_test_notify(args: argparse.Namespace) -> int:
    config = get_config()
    setup_logging(config.log_level)
    db.init_db(config.db_path)

    from .notify import ExpoNotifier, WebhookNotifier

    with db.closing_connection(config.db_path) as conn:
        tokens = [r["expo_push_token"] for r in conn.execute("SELECT expo_push_token FROM devices")]

    title = "Test alert"
    body = "If you can see this, alerts are wired up correctly."

    delivered = 0
    if tokens:
        result = ExpoNotifier(config.expo_access_token).send(tokens, title, body)
        delivered += result.sent
        print(f"Expo: sent to {result.sent}, errors {result.errors}")
        for message in result.error_messages:
            print(f"  ! {message}")
    else:
        print("No paired devices; skipping Expo push.")

    webhook = os.environ.get("TGTG_WEBHOOK_URL")
    if webhook:
        result = WebhookNotifier(webhook).send([], title, body)
        delivered += result.sent
        print(f"Webhook: {'ok' if result.ok else 'failed'}")

    if not tokens and not webhook:
        print("Nothing to send to. Pair a phone or set TGTG_WEBHOOK_URL.", file=sys.stderr)
        return 1

    return 0 if delivered else 1


def cmd_serve(args: argparse.Namespace) -> int:
    config = get_config()
    setup_logging(config.log_level)
    db.init_db(config.db_path)

    if args.only == "api":
        _serve_api(config)
        return 0
    if args.only == "poller":
        from .poller import Poller

        Poller(config, webhook_url=os.environ.get("TGTG_WEBHOOK_URL")).run_forever()
        return 0

    # Both in one process: the common self-hosted case, one container, no
    # supervisor. The poller runs on a daemon thread so Ctrl-C stops both.
    import threading

    from .poller import Poller

    poller = Poller(config, webhook_url=os.environ.get("TGTG_WEBHOOK_URL"))
    thread = threading.Thread(target=poller.run_forever, name="poller", daemon=True)
    thread.start()
    try:
        _serve_api(config)
    finally:
        poller.stop()
    return 0


def _serve_api(config: Config) -> None:
    import uvicorn

    from .api import create_app

    print(f"API listening on http://{config.host}:{config.port}")
    uvicorn.run(create_app(config), host=config.host, port=config.port, log_level="info")


# -- parser --------------------------------------------------------------


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="tgtg-alert",
        description="Watch Too Good To Go for specific bags and push an alert when they appear.",
    )
    parser.add_argument("--version", action="version", version=f"tgtg-alert {__version__}")
    parser.add_argument("--env-file", default=ENV_FILENAME, help="path to the env file (default: ./.env)")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("init", help="create the env file and database")
    p.add_argument("--force", action="store_true", help="overwrite an existing env file")
    p.set_defaults(func=cmd_init)

    p = sub.add_parser("login", help="log in to Too Good To Go (interactive, one time)")
    p.add_argument("--email", help="account email; prompted if omitted")
    p.set_defaults(func=cmd_login)

    watch = sub.add_parser("watch", help="manage watches").add_subparsers(
        dest="watch_command", required=True
    )

    p = watch.add_parser("add", help="add a watch")
    p.add_argument("--lat", type=float, required=True, help="centre latitude")
    p.add_argument("--lon", type=float, required=True, help="centre longitude")
    p.add_argument("--radius", type=int, default=10, help="search radius in km (default 10)")
    p.add_argument("--store", help="substring of the store name, case-insensitive")
    p.add_argument("--bag", help="substring of the bag name, e.g. 'Magic Bag'")
    p.add_argument("--max-price", type=float, help="only alert at or below this price")
    p.add_argument("--label", help="a name for this watch")
    p.add_argument(
        "--notify-on-increase",
        action="store_true",
        help="also alert when an available bag's count rises (noisy; off by default)",
    )
    p.set_defaults(func=cmd_watch_add)

    p = watch.add_parser("list", help="list watches")
    p.set_defaults(func=cmd_watch_list)

    p = watch.add_parser("update", help="change or re-baseline a watch")
    p.add_argument("watch_id", type=int)
    p.add_argument("--enable", action="store_true")
    p.add_argument("--disable", action="store_true")
    p.add_argument("--store", help="set the store pattern (empty string clears it)")
    p.add_argument("--bag", help="set the bag pattern (empty string clears it)")
    p.add_argument(
        "--rebaseline",
        action="store_true",
        help="forget current stock so the next poll re-surveys silently",
    )
    p.set_defaults(func=cmd_watch_update)

    p = watch.add_parser("rm", help="delete a watch")
    p.add_argument("watch_id", type=int)
    p.set_defaults(func=cmd_watch_rm)

    p = sub.add_parser("devices", help="list or remove paired phones")
    p.add_argument("--rm", type=int, metavar="ID", help="remove the device with this id")
    p.set_defaults(func=cmd_devices)

    p = sub.add_parser("pair", help="show a QR code to pair the phone app")
    p.add_argument("--url", help="the URL the phone should use (default: this host's LAN IP)")
    p.set_defaults(func=cmd_pair)

    p = sub.add_parser("poll", help="run a single poll pass and exit")
    p.add_argument("--dry-run", action="store_true", help="report what would alert, send nothing")
    p.set_defaults(func=cmd_poll)

    p = sub.add_parser("test-notify", help="send a test push to paired devices")
    p.set_defaults(func=cmd_test_notify)

    p = sub.add_parser("serve", help="run the API and the poller")
    p.add_argument(
        "--only",
        choices=["api", "poller", "both"],
        default="both",
        help="run just one half (useful for splitting across containers)",
    )
    p.set_defaults(func=cmd_serve)

    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    load_env_file(Path(args.env_file) if args.env_file else None)
    try:
        return args.func(args)
    except KeyboardInterrupt:
        print("\nInterrupted.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    sys.exit(main())
